qint64 pasteboardChangeCount()
{
    return static_cast<qint64>(NSPasteboard.generalPasteboard.changeCount);
}

bool pasteboardIsConcealed()
{
    // http://nspasteboard.org — markers used by password managers.
    static NSSet<NSString*>* const markers = [NSSet setWithArray:@[
        @"org.nspasteboard.ConcealedType",
        @"org.nspasteboard.TransientType",
        @"org.nspasteboard.AutoGeneratedType",
        @"com.agilebits.onepassword",
        @"com.typeit4me.clipping",
        @"de.petermaurer.TransientPasteboardType",
    ]];
    for (NSPasteboardType type in NSPasteboard.generalPasteboard.types) {
        if ([markers containsObject:type])
            return true;
    }
    return false;
}

AppInfo frontmostApp()
{
    NSRunningApplication* app = NSWorkspace.sharedWorkspace.frontmostApplication;
    if (!app || isSelf(app))
        return {};
    return { QString::fromNSString(app.localizedName ?: @""),
             QString::fromNSString(app.bundleIdentifier ?: @"") };
}

QByteArray appIconPng(const QString& bundleId, int pixelSize)
{
    @autoreleasepool {
        NSURL* url = [NSWorkspace.sharedWorkspace URLForApplicationWithBundleIdentifier:bundleId.toNSString()];
        if (!url)
            return {};
        NSImage* icon = [NSWorkspace.sharedWorkspace iconForFile:url.path];
        if (!icon)
            return {};

        NSBitmapImageRep* rep = [[NSBitmapImageRep alloc]
            initWithBitmapDataPlanes:nullptr
                          pixelsWide:pixelSize
                          pixelsHigh:pixelSize
                       bitsPerSample:8
                     samplesPerPixel:4
                            hasAlpha:YES
                            isPlanar:NO
                      colorSpaceName:NSCalibratedRGBColorSpace
                         bytesPerRow:0
                        bitsPerPixel:0];
        if (!rep)
            return {};
        rep.size = NSMakeSize(pixelSize, pixelSize);

        [NSGraphicsContext saveGraphicsState];
        NSGraphicsContext.currentContext = [NSGraphicsContext graphicsContextWithBitmapImageRep:rep];
        [icon drawInRect:NSMakeRect(0, 0, pixelSize, pixelSize)
                fromRect:NSZeroRect
               operation:NSCompositingOperationCopy
                fraction:1.0];
        [NSGraphicsContext restoreGraphicsState];

        NSData* png = [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
        return png ? QByteArray::fromNSData(png) : QByteArray();
    }
}

void rememberFrontmostApp()
{
    NSRunningApplication* app = NSWorkspace.sharedWorkspace.frontmostApplication;
    if (app && !isSelf(app))
        g_previousApp = app;
}

void restorePreviousApp()
{
    [NSApp hide:nil];
    if (g_previousApp && !g_previousApp.terminated)
        [g_previousApp activateWithOptions:0];
}

void activateSelf()
{
    [NSApp unhide:nil];
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
    // The replacement (-activate) is cooperative and may be refused when the
    // user is in another app; for a hotkey-invoked popup we want focus now.
    [NSApp activateIgnoringOtherApps:YES];
#pragma clang diagnostic pop
    if (@available(macOS 14.0, *))
        [NSApp activate];
}

bool isAccessibilityTrusted(bool promptUser)
{
    if (!promptUser)
        return AXIsProcessTrusted();
    NSDictionary* options = @{ (__bridge NSString*)kAXTrustedCheckOptionPrompt: @YES };
    return AXIsProcessTrustedWithOptions((__bridge CFDictionaryRef)options);
}

void openAccessibilitySettings()
{
    NSURL* url = [NSURL URLWithString:@"x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"];
    [NSWorkspace.sharedWorkspace openURL:url];
}

bool sendPasteKeystroke()
{
    if (!AXIsProcessTrusted())
        return false;

    CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateCombinedSessionState);
    CGEventRef down = CGEventCreateKeyboardEvent(source, static_cast<CGKeyCode>(kVK_ANSI_V), true);
    CGEventRef up = CGEventCreateKeyboardEvent(source, static_cast<CGKeyCode>(kVK_ANSI_V), false);
    CGEventSetFlags(down, kCGEventFlagMaskCommand);
    CGEventSetFlags(up, kCGEventFlagMaskCommand);
    CGEventPost(kCGAnnotatedSessionEventTap, down);
    CGEventPost(kCGAnnotatedSessionEventTap, up);
    CFRelease(down);
    CFRelease(up);
    if (source)
        CFRelease(source);
    return true;
}

bool registerGlobalHotkey(int preset, std::function<void()> callback)
{
    g_hotkeyCallback = std::move(callback);

    if (!g_hotkeyHandler) {
        EventTypeSpec spec = { kEventClassKeyboard, kEventHotKeyPressed };
        InstallApplicationEventHandler(&onHotkey, 1, &spec, nullptr, &g_hotkeyHandler);
    }
    if (g_hotkeyRef) {
        UnregisterEventHotKey(g_hotkeyRef);
        g_hotkeyRef = nullptr;
    }

    const HotkeyDef def = hotkeyFor(preset);
    const EventHotKeyID hotkeyId = { 0x434C5354 /* 'CLST' */, 1 };
    const OSStatus status = RegisterEventHotKey(def.keyCode, def.modifiers, hotkeyId,
                                                GetApplicationEventTarget(), 0, &g_hotkeyRef);
    return status == noErr;
}

