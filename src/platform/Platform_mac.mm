std::function<void()> g_hotkeyCallback;
EventHotKeyRef g_hotkeyRef = nullptr;
EventHandlerRef g_hotkeyHandler = nullptr;

struct HotkeyDef {
    UInt32 keyCode;
    UInt32 modifiers;
};

// Keep in sync with hotkeyPresets().
HotkeyDef hotkeyFor(int preset)
{
    switch (preset) {
    case 1: return { kVK_Space, optionKey };
    case 2: return { kVK_ANSI_V, controlKey | optionKey };
    default: return { kVK_ANSI_V, cmdKey | shiftKey };
    }
}

OSStatus onHotkey(EventHandlerCallRef, EventRef, void*)
{
    if (g_hotkeyCallback) {
        // Defer: never run app logic inside a Carbon callback.
        auto callback = g_hotkeyCallback;
        dispatch_async(dispatch_get_main_queue(), ^{ callback(); });
    }
    return noErr;
}

bool isSelf(NSRunningApplication* app)
{
    return app && app.processIdentifier == NSProcessInfo.processInfo.processIdentifier;
}

NSImage* roundedMask(CGFloat radius)
{
    const CGFloat edge = 2.0 * radius + 1.0;
    NSImage* mask = [NSImage imageWithSize:NSMakeSize(edge, edge)
                                   flipped:NO
                            drawingHandler:^BOOL(NSRect rect) {
                                [NSColor.blackColor setFill];
                                [[NSBezierPath bezierPathWithRoundedRect:rect xRadius:radius yRadius:radius] fill];
                                return YES;
                            }];
    mask.capInsets = NSEdgeInsetsMake(radius, radius, radius, radius);
    mask.resizingMode = NSImageResizingModeStretch;
    return mask;
}

