{
    return { QStringLiteral("⌘⇧V"), QStringLiteral("⌥Space"), QStringLiteral("⌃⌥V") };
}

void prepareWindow(QWindow* window, const QRect& card, int radius, bool dark, bool glass)
{
    if (!window)
        return;
    NSView* view = (__bridge NSView*)reinterpret_cast<void*>(window->winId());
    NSWindow* nsWindow = view.window;
    if (!view || !nsWindow)
        return;

    nsWindow.collectionBehavior = NSWindowCollectionBehaviorCanJoinAllSpaces
                                | NSWindowCollectionBehaviorFullScreenAuxiliary;
    nsWindow.opaque = NO;
    nsWindow.backgroundColor = NSColor.clearColor;
    nsWindow.hidesOnDeactivate = NO;

    if (!glass) {
        [g_effectView removeFromSuperview];
        g_effectView = nil;
        nsWindow.hasShadow = NO;   // QML draws its own shadow in this mode
        return;
    }

    // Place a frosted-glass view *behind* Qt's content view, sized to the card.
    NSView* host = view.superview;
    if (!host)
        return;

    if (!g_effectView) {
        g_effectView = [[NSVisualEffectView alloc] initWithFrame:NSZeroRect];
        g_effectView.blendingMode = NSVisualEffectBlendingModeBehindWindow;
        g_effectView.state = NSVisualEffectStateActive;
        g_effectView.material = NSVisualEffectMaterialHUDWindow;
    }
    g_effectView.appearance = [NSAppearance appearanceNamed:dark ? NSAppearanceNameDarkAqua : NSAppearanceNameAqua];
    g_effectView.maskImage = roundedMask(radius);

    const NSRect vf = view.frame;
    const CGFloat y = host.isFlipped ? vf.origin.y + card.y()
                                     : vf.origin.y + (vf.size.height - card.y() - card.height());
    g_effectView.frame = NSMakeRect(vf.origin.x + card.x(), y, card.width(), card.height());

    if (g_effectView.superview != host) {
        [g_effectView removeFromSuperview];
        [host addSubview:g_effectView positioned:NSWindowBelow relativeTo:view];
    }

    // Native shadow follows the alpha of the window content -> hugs the card.
    nsWindow.hasShadow = YES;
    [nsWindow invalidateShadow];
}

void bringToFront(QWindow* window)
{
    if (!window)
        return;
    NSView* view = (__bridge NSView*)reinterpret_cast<void*>(window->winId());
    NSWindow* nsWindow = view.window;
    if (!nsWindow)
        return;

    // Qt::Tool maps to NSPanel, which by default hides as soon as the app is
    // not active. A menu-bar agent is often *not* made active by macOS 14+,
    // so without this the popup flashes and disappears.
    nsWindow.hidesOnDeactivate = NO;
    nsWindow.level = NSFloatingWindowLevel;
    nsWindow.collectionBehavior = NSWindowCollectionBehaviorCanJoinAllSpaces
                                | NSWindowCollectionBehaviorFullScreenAuxiliary;
    activateSelf();
    [nsWindow orderFrontRegardless];
    [nsWindow makeKeyAndOrderFront:nil];
}

bool launchAtLoginEnabled()
{
    if (@available(macOS 13.0, *)) {
        const SMAppServiceStatus st = SMAppService.mainAppService.status;
        return st == SMAppServiceStatusEnabled || st == SMAppServiceStatusRequiresApproval;
    }
    return false;
}

bool setLaunchAtLogin(bool enable, QString* error)
{
    if (@available(macOS 13.0, *)) {
        SMAppService* service = SMAppService.mainAppService;
        NSError* err = nil;
        const BOOL ok = enable ? [service registerAndReturnError:&err]
                               : [service unregisterAndReturnError:&err];
        if (!ok) {
            if (error)
                *error = QString::fromNSString(err.localizedDescription ?: @"unknown error");
            return false;
        }
        if (enable && service.status == SMAppServiceStatusRequiresApproval) {
            // User switched the item off earlier: macOS wants explicit consent.
            [SMAppService openSystemSettingsLoginItems];
            if (error)
                *error = QStringLiteral("Подтверди ClipStash в «Объектах входа»");
        }
        return true;
    }
    if (error)
        *error = QStringLiteral("Нужна macOS 13 или новее");
    return false;
}

